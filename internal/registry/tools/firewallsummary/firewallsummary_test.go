func TestParseNftRuleset(t *testing.T) {
	t.Parallel()

	t.Run("full ruleset", func(t *testing.T) {
		t.Parallel()
		tables, total, rules, truncated, err := parseNftRuleset([]byte(nftFixture), "", "")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if truncated || rules != nil {
			t.Errorf("expected no rendered rules without a filter, got %v (truncated=%v)", rules, truncated)
		}
		if total != 3 {
			t.Errorf("expected 3 total rules, got %d", total)
		}
		if len(tables) != 2 {
			t.Fatalf("expected 2 tables, got %d: %+v", len(tables), tables)
		}

		filter := tables[0]
		if filter.Name != "filter" || filter.Family != "inet" {
			t.Errorf("unexpected table 0: %+v", filter)
		}
		if len(filter.Chains) != 2 {
			t.Fatalf("expected 2 chains in filter, got %d", len(filter.Chains))
		}
		input := filter.Chains[0]
		if input.Name != "input" || input.Policy != "accept" || input.RuleCount != 2 {
			t.Errorf("unexpected input chain: %+v", input)
		}
		if input.Packets != 107 || input.Bytes != 8420 {
			t.Errorf("expected counter sums 107/8420, got %d/%d", input.Packets, input.Bytes)
		}
		forward := filter.Chains[1]
		if forward.Name != "forward" || forward.Policy != "drop" || forward.RuleCount != 0 {
			t.Errorf("unexpected forward chain: %+v", forward)
		}

		nat := tables[1]
		if nat.Name != "nat" || nat.Family != "ip" || len(nat.Chains) != 1 || nat.Chains[0].RuleCount != 1 {
			t.Errorf("unexpected nat table: %+v", nat)
		}
	})

	t.Run("chain filter renders rules", func(t *testing.T) {
		t.Parallel()
		_, _, rules, truncated, err := parseNftRuleset([]byte(nftFixture), "filter", "input")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if truncated {
			t.Error("expected no truncation for 2 rules")
		}
		if len(rules) != 2 {
			t.Fatalf("expected 2 rendered rules, got %d: %v", len(rules), rules)
		}
		if !strings.Contains(rules[0], "handle 4") || !strings.Contains(rules[0], "iifname") {
			t.Errorf("unexpected rendered rule 0: %q", rules[0])
		}
		if !strings.Contains(rules[1], "drop bogons") {
			t.Errorf("expected comment in rendered rule 1: %q", rules[1])
		}
	})

	t.Run("rule cap at 100", func(t *testing.T) {
		t.Parallel()
		var sb strings.Builder
		sb.WriteString(`{"nftables": [{"table": {"family": "ip", "name": "big", "handle": 1}},`)
		sb.WriteString(`{"chain": {"family": "ip", "table": "big", "name": "c", "handle": 1, "policy": "accept"}}`)
		for i := 0; i < 150; i++ {
			fmt.Fprintf(&sb, `,{"rule": {"family": "ip", "table": "big", "chain": "c", "handle": %d, "expr": [{"accept": null}]}}`, i+10)
		}
		sb.WriteString(`]}`)

		tables, total, rules, truncated, err := parseNftRuleset([]byte(sb.String()), "big", "c")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if total != 150 || tables[0].Chains[0].RuleCount != 150 {
			t.Errorf("expected 150 counted rules, got total=%d", total)
		}
		if len(rules) != 100 || !truncated {
			t.Errorf("expected 100 rendered rules with truncation, got %d (truncated=%v)", len(rules), truncated)
		}
	})

	t.Run("empty ruleset", func(t *testing.T) {
		t.Parallel()
		tables, total, _, _, err := parseNftRuleset([]byte(nftEmptyFixture), "", "")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if len(tables) != 0 || total != 0 {
			t.Errorf("expected empty ruleset, got %d tables / %d rules", len(tables), total)
		}
	})

	t.Run("invalid JSON", func(t *testing.T) {
		t.Parallel()
		if _, _, _, _, err := parseNftRuleset([]byte("not json"), "", ""); err == nil {
			t.Error("expected error for invalid JSON")
		}
	})
}

