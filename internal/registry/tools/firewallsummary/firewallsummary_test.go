func TestParseIptablesSave(t *testing.T) {
	t.Parallel()

	t.Run("save format with counters", func(t *testing.T) {
		t.Parallel()
		tables, total, rules, truncated, err := parseIptablesSave([]byte(iptablesSaveFixture), "", "")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if truncated || rules != nil {
			t.Errorf("expected no rendered rules without filter, got %v", rules)
		}
		if total != 4 {
			t.Errorf("expected 4 total rules, got %d", total)
		}
		if len(tables) != 2 {
			t.Fatalf("expected 2 tables, got %d: %+v", len(tables), tables)
		}

		filter := tables[0]
		if filter.Name != "filter" || filter.Family != "ip" || len(filter.Chains) != 4 {
			t.Fatalf("unexpected filter table: %+v", filter)
		}
		input := filter.Chains[0]
		if input.Name != "INPUT" || input.Policy != "ACCEPT" || input.RuleCount != 2 {
			t.Errorf("unexpected INPUT chain: %+v", input)
		}
		if input.Packets != 530 || input.Bytes != 37236 {
			t.Errorf("expected policy counters 530/37236, got %d/%d", input.Packets, input.Bytes)
		}
		docker := filter.Chains[3]
		if docker.Name != "DOCKER-USER" || docker.Policy != "" {
			t.Errorf("expected user chain without policy, got %+v", docker)
		}

		nat := tables[1]
		if nat.Name != "nat" || len(nat.Chains) != 2 || nat.Chains[1].RuleCount != 1 {
			t.Errorf("unexpected nat table: %+v", nat)
		}
	})

	t.Run("chain filter renders raw rules", func(t *testing.T) {
		t.Parallel()
		_, _, rules, _, err := parseIptablesSave([]byte(iptablesSaveFixture), "filter", "INPUT")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if len(rules) != 2 {
			t.Fatalf("expected 2 rendered rules, got %d: %v", len(rules), rules)
		}
		if !strings.Contains(rules[0], "-A INPUT -i lo -j ACCEPT") {
			t.Errorf("unexpected rendered rule: %q", rules[0])
		}
	})

	t.Run("iptables -S format with implicit filter table", func(t *testing.T) {
		t.Parallel()
		tables, total, _, _, err := parseIptablesSave([]byte(iptablesSFixture), "", "")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if total != 2 {
			t.Errorf("expected 2 rules, got %d", total)
		}
		if len(tables) != 1 || tables[0].Name != "filter" {
			t.Fatalf("expected implicit filter table, got %+v", tables)
		}
		if len(tables[0].Chains) != 4 {
			t.Errorf("expected 4 chains (3 builtin + MYCHAIN), got %+v", tables[0].Chains)
		}
		if tables[0].Chains[1].Name != "FORWARD" || tables[0].Chains[1].Policy != "DROP" {
			t.Errorf("unexpected FORWARD chain: %+v", tables[0].Chains[1])
		}
	})

	t.Run("empty input", func(t *testing.T) {
		t.Parallel()
		tables, total, _, _, err := parseIptablesSave([]byte(""), "", "")
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if len(tables) != 0 || total != 0 {
			t.Errorf("expected empty result, got %+v", tables)
		}
	})
}

