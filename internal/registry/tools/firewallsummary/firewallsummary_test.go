// mockLookPath returns an execLookPath stub where only the listed binaries exist.
func mockLookPath(available ...string) func(string) (string, error) {
	return func(file string) (string, error) {
		for _, a := range available {
			if a == file {
				return "/mock/bin/" + file, nil
			}
		}
		return "", errors.New("executable file not found in $PATH")
	}
}

// mockTool builds a tool whose exec layer serves canned output per binary name.
func mockTool(t testing.TB, outputs map[string]string, available ...string) *Tool {
	t.Helper()
	tool := New()
	tool.execLookPath = mockLookPath(available...)
	tool.execCommand = func(ctx context.Context, name string, args ...string) ([]byte, error) {
		// Unwrap 'sudo -n <binary> ...' invocations.
		binary := name
		if name == "sudo" && len(args) >= 2 {
			binary = args[1]
		}
		if out, ok := outputs[binary]; ok {
			return []byte(out), nil
		}
		return nil, fmt.Errorf("mock: no output configured for %q", binary)
	}
	return tool
}

func TestContractCompliance(t *testing.T) {
	t.Parallel()

	tool := New()
	var _ registry.Tool = tool

	if tool.Name() != "get_firewall_summary" {
		t.Errorf("expected Name() == 'get_firewall_summary', got %q", tool.Name())
	}
	if tool.Category() != registry.CategoryNetwork {
		t.Errorf("expected Category() == network, got %q", tool.Category())
	}
	if tool.Hidden() {
		t.Error("expected Hidden() == false")
	}
	if tool.Description() == "" {
		t.Error("expected non-empty Description()")
	}
	help := tool.Help()
	for _, src := range []string{"nft -j list ruleset", "iptables-save"} {
		if !strings.Contains(help, src) {
			t.Errorf("Help() must reference data source %q", src)
		}
	}

	params := tool.Parameters()
	if len(params) != 2 {
		t.Fatalf("expected 2 parameters (table, chain), got %d", len(params))
	}
	names := map[string]bool{}
	for _, p := range params {
		names[p.Name] = true
		if p.Required {
			t.Errorf("parameter %q must be optional", p.Name)
		}
		if p.Type != "string" {
			t.Errorf("parameter %q must be a string, got %q", p.Name, p.Type)
		}
	}
	if !names["table"] || !names["chain"] {
		t.Errorf("expected parameters named 'table' and 'chain', got %v", names)
	}
}

